    function todayStr() {
        var d = new Date();
        return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
    }

    function loadState() {
        try { return JSON.parse(localStorage.getItem(STATE_KEY)) || {}; } catch (e) {}
        return {};
    }
    function saveState(s) {
        try { localStorage.setItem(STATE_KEY, JSON.stringify(s)); } catch (e) {}
    }

    // 基于本地日期字符串做确定性哈希，保证每天 0 点自动切换、全设备同天同条
    function dateHash(str) {
        var h = 0;
        for (var i = 0; i < str.length; i++) {
            h = ((h << 5) - h) + str.charCodeAt(i);
            h |= 0;
        }
        return Math.abs(h);
    }

    var currentDate = todayStr();
    var dayIndex = dateHash(currentDate);
    var offset = 0;

    function getDayIndex() {
        var t = todayStr();
        if (t !== currentDate) {
            // 日期变了：重置偏移量并更新 dayIndex
            currentDate = t;
            dayIndex = dateHash(currentDate);
            offset = 0;
        }
        return dayIndex;
    }

    function getTip(i) {
        var di = getDayIndex();
        var idx = ((di + i) % TIPS.length + TIPS.length) % TIPS.length;
        return TIPS[idx];
    }

    function isPermanentOff() {
        var s = loadState();
        if (new URLSearchParams(window.location.search).get('tips') === '1') return false;
        return s.off === true;
    }
    function isHiddenToday() {
        return loadState().hiddenDate === todayStr();
    }

    function setPermanentOff(v) {
        var s = loadState();
        s.off = !!v;
        if (!v) delete s.hiddenDate;
        saveState(s);
        renderBanner();
    }

    function hideToday() {
        var s = loadState();
        s.hiddenDate = todayStr();
        saveState(s);
        renderBanner();
    }

